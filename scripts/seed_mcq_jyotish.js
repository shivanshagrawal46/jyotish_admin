const DRY = process.argv.includes('--dry-run');

(async () => {
  await mongoose.connect(process.env.MONGODB_URI);

  let catsAdded = 0;
  let mastersAdded = 0;
  let questionsAdded = 0;
  let questionsSkipped = 0;

  for (const block of DATA) {
    let category = await McqCategory.findOne({ name: block.category });
    if (!category) {
      if (DRY) {
        console.log(`+ category: ${block.category}`);
      } else {
        category = await new McqCategory({
          name: block.category,
          position: block.position,
          introduction: block.introduction || '',
        }).save();
        catsAdded += 1;
        console.log(`+ category: ${category.name} (id=${category.id})`);
      }
    } else {
      console.log(`= category exists: ${category.name} (id=${category.id})`);
    }
    if (DRY && !category) continue;

    const existingMasters = await McqMaster.find({ category: category._id }).lean();
    let nextPos = existingMasters.reduce((m, x) => Math.max(m, x.position || 0), 0);

    for (const m of block.masters) {
      let master = await McqMaster.findOne({ category: category._id, name: m.name });
      if (!master) {
        nextPos += 1;
        if (DRY) {
          console.log(`  + subcategory: ${m.name} (${m.questions.length} questions)`);
          continue;
        }
        master = await new McqMaster({
          category: category._id,
          name: m.name,
          position: nextPos,
          introduction: m.introduction || '',
        }).save();
        mastersAdded += 1;
        console.log(`  + subcategory: ${master.name} (id=${master.id})`);
      } else {
        console.log(`  = subcategory exists: ${master.name} (id=${master.id})`);
      }

      for (const item of m.questions) {
        const exists = await McqContent.findOne({ master: master._id, question: item.question }).lean();
        if (exists) {
          questionsSkipped += 1;
          continue;
        }
        if (DRY) {
          questionsAdded += 1;
          continue;
        }
        await new McqContent({
          master: master._id,
          question: item.question,
          option1: item.option1,
          option2: item.option2,
          option3: item.option3,
          option4: item.option4,
          correctAnswers: item.correctAnswers,
          explanation: item.explanation,
          references: [],
          isActive: true,
        }).save();
        questionsAdded += 1;
      }
      console.log(`      questions now: ${await McqContent.countDocuments({ master: master._id })}`);
    }
  }

  console.log(`\n${DRY ? '[dry run] ' : ''}categories added: ${catsAdded}, subcategories added: ${mastersAdded}, questions added: ${questionsAdded}, already present: ${questionsSkipped}`);
  await mongoose.disconnect();
})().catch(async (e) => { console.error('FAILED:', e); await mongoose.disconnect(); process.exit(1); });
